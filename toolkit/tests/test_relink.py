def test_unknown_type_fails_on_unsupported(make_engagement, tmp_path, quiet, capfd):
    model = tmp_path / "model"
    shutil.copytree(MODEL, model)
    schema = json.loads((model / "schema.json").read_text(encoding="utf-8"))
    schema["tables"][0]["columns"][1]["type"] = "money"
    (model / "schema.json").write_text(json.dumps(schema), encoding="utf-8")
