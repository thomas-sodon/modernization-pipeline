EXPECTED = {
    "text": ("varchar(40)", "nvarchar(40)"),
    "memo": ("text", "nvarchar(max)"),
    "byte": ("smallint", "tinyint"),
    "integer": ("smallint", "smallint"),
    "longinteger": ("integer", "int"),
    "autonumber": ("integer", "int"),
    "single": ("real", "real"),
    "double": ("double precision", "float(53)"),
    "currency": ("numeric(19,4)", "decimal(19,4)"),
    "decimal": ("numeric(12,3)", "decimal(12,3)"),
    "datetime": ("timestamp(0)", "datetime2(0)"),
    "yesno": ("boolean", "bit"),
    "hyperlink": ("text", "nvarchar(max)"),
    "guid": ("uuid", "uniqueidentifier"),
}
DDL_SUFFIX = {
    "autonumber": ("integer GENERATED BY DEFAULT AS IDENTITY", "int IDENTITY(1,1)"),
    "yesno": ("boolean NOT NULL DEFAULT false", "bit NOT NULL DEFAULT 0"),
}


def _normalize(compiled: str, dialect: str) -> str:
    text = compiled.lower().replace(", ", ",").replace(" without time zone", "")
    if dialect == "mssql" and text == "integer":
        text = "int"
    return text


@pytest.mark.parametrize("neutral", sorted(EXPECTED))
@pytest.mark.parametrize("dialect", typemap.DIALECTS)
def test_every_typemap_entry_for_both_dialects(neutral, dialect):
    col = {"name": "c", "type": neutral, "size": 40, "precision": 12, "scale": 3}
    i = typemap.DIALECTS.index(dialect)
    assert typemap.sql_type(col, dialect) == EXPECTED[neutral][i]
    assert typemap.ddl(col, dialect) == DDL_SUFFIX.get(neutral, EXPECTED[neutral])[i]
    d = postgresql.dialect() if dialect == "postgresql" else mssql.dialect()
    compiled = typemap.sa_type(col).compile(dialect=d)
    assert _normalize(compiled, dialect) == EXPECTED[neutral][i]


def test_typemap_covers_the_whole_vocabulary():
    assert set(EXPECTED) | set(typemap.OMITTED_TYPES) == set(typemap.NEUTRAL_TYPES)
    assert set(EXPECTED) == set(typemap.MAPPED_TYPES)


def test_text_and_decimal_defaults():
    assert typemap.sql_type({"type": "text", "size": None}, "postgresql") == "varchar(255)"
    assert typemap.sql_type({"type": "decimal"}, "mssql") == "decimal(18,0)"


def test_omitted_and_unsupported_types():
    for t in ("complex", "oleobject"):
        assert typemap.sql_type({"type": t}, "postgresql") is None
        assert typemap.sa_type({"type": t}) is None
        assert typemap.is_supported(t)
    with pytest.raises(typemap.UnsupportedType):
        typemap.sql_type({"type": "money"}, "mssql")
    assert not typemap.is_supported("money")


def test_identity_yesno_and_rowversion_columns_compile():
    table_model = {
        "name": "T",
        "columns": [
            {"name": "ID", "type": "autonumber"},
            {"name": "Flag", "type": "yesno"},
            {"name": "W", "type": "double"},
        ],
    }
    for dialect, d, identity, default in (
        ("postgresql", postgresql.dialect(), "GENERATED BY DEFAULT AS IDENTITY", "DEFAULT false"),
        ("mssql", mssql.dialect(), "IDENTITY(1,1)", "DEFAULT 0"),
    ):
        md = MetaData()
        cols = [typemap.sa_column(c, primary_key=c["name"] == "ID") for c in table_model["columns"]]
        cols += typemap.extra_columns(table_model, dialect)
        ddl = str(CreateTable(Table("T", md, *cols)).compile(dialect=d))
        assert identity in ddl
        flag = next(x for x in ddl.split("\n") if "Flag" in x)
        assert default in flag and "NOT NULL" in flag
        assert ("mp_rowversion ROWVERSION" in ddl) == (dialect == "mssql")
    assert typemap.needs_rowversion(table_model)
    assert not typemap.needs_rowversion({"columns": [{"type": "text"}]})


