def test_identity_writes_with_and_without_dbseechanges(rendered):
    body = _section(rendered[2], "IDENTITY tables written from code")
    rows = [r for r in body.split("\n") if r.startswith("| `")]
    found = {(r.split("|")[1].strip(), int(r.split("|")[2])) for r in rows}
    no_see = _line_of('OpenRecordset("Gizmos", dbOpenDynaset)')
    see = _line_of('OpenRecordset("Gizmos", _')
    continued = _line_of('OpenRecordset("SELECT * FROM Bins", _')
    execute = _line_of("CurrentDb.Execute strSQL")
    runsql = _line_of("DoCmd.RunSQL")
    commented = _line_of("' Set rsOld")
    assert ("`modFixture.AddGizmoNoSee`", no_see) in found
    assert ("`modFixture.AddBinContinued`", continued) in found  # type on the continued line
    assert ("`modFixture.CommentedOut`", execute) in found  # dbSeeChanges only in a comment
    assert ("`modFixture.CommentedOut`", runsql) in found
    assert all(line != see for _, line in found)  # dbSeeChanges across a continuation
    assert all(line != commented for _, line in found)  # call inside a comment
    assert "`modFixture.AddGizmoSee`" not in body
    assert "| `modFixture.FindBin`" not in body  # dbOpenTable is not a dynaset write
    row = next(r for r in rows if f"| {execute} |" in r)
    assert "`Gizmos`" in row and "DELETE" in row and "SQL Server" in row
    main = body.split("### ")[0]
    assert "PostgreSQL" not in main


