def _engagement(make_engagement, tmp_path, **fields):
    source = {"kind": "accdt", "external_links": LINKS, **fields.pop("source", {})}
    eng = make_engagement(tmp_path, source=source, **fields)
    target = tmp_path / "target" / "app" / "analysis"
    target.mkdir(parents=True, exist_ok=True)
    (target / "rules.json").write_text(json.dumps(RULES), encoding="utf-8")
    return eng


def _run(eng, model, out, *extra, capfd=None):
    code = cli.main(
        [
            "relink-scan",
            str(eng),
            "--model",
            str(model),
            "--dialects",
            "from-engagement",
            "--out",
            str(out),
            "--fail-on",
            "unsupported-type",
            *extra,
        ]
    )
    summary = None
    if capfd is not None:
        lines = [x for x in capfd.readouterr().out.splitlines() if x.strip()]
        summary = json.loads(lines[-1]) if lines else None
    return code, summary


def _section(md: str, title: str) -> str:
    return relink.split_sections(md)[title]


def _line_of(fragment: str) -> int:
    for i, line in enumerate(CODE.read_text(encoding="utf-8").split("\n"), 1):
        if fragment in line:
            return i
    raise AssertionError(fragment)


