def test_same_inputs_same_bytes_and_one_line_change_differs(make_engagement, tmp_path):
    eng = _engagement(make_engagement, tmp_path)
    a, b, c = tmp_path / "a.md", tmp_path / "b.md", tmp_path / "c.md"
    assert _run(eng, MODEL, a)[0] == 0
    assert _run(eng, MODEL, b)[0] == 0
    assert a.read_bytes() == b.read_bytes()
    model = tmp_path / "model"
    shutil.copytree(MODEL, model)
    text = (model / "schema.json").read_text(encoding="utf-8")
    text = text.replace('"primary_key": [],', '"primary_key": ["Msg"],', 1)
    (model / "schema.json").write_text(text, encoding="utf-8")
    assert _run(eng, model, c)[0] == 0
    assert c.read_bytes() != a.read_bytes()
    assert "`LogLines`" not in _section(c.read_text(encoding="utf-8"), "Tables without a primary key")


def test_check_passes_fails_and_never_writes(make_engagement, tmp_path, quiet, capfd):
    eng = _engagement(make_engagement, tmp_path)
    out = tmp_path / "changes.md"
    assert _run(eng, MODEL, out, capfd=capfd)[0] == 0
    before = out.read_bytes()
    mtime = out.stat().st_mtime_ns

    code, summary = _run(eng, MODEL, out, "--check", capfd=capfd)
    assert code == 0 and summary["status"] == "ok"
    assert out.stat().st_mtime_ns == mtime

    edited = before.decode("utf-8").replace("| `Gizmos.Active` |", "| `Gizmos.Activ` |", 1)
    out.write_bytes(edited.encode("utf-8"))
    code, summary = _run(eng, MODEL, out, "--check", capfd=capfd)
    assert code == 1
    assert any("Yes/No fields" in m for m in summary["messages"])
    assert out.read_bytes() == edited.encode("utf-8")

    out.unlink()
    code, summary = _run(eng, MODEL, out, "--check", capfd=capfd)
    assert code == 1
    assert any("missing" in m for m in summary["messages"])
    assert not out.exists()


