"""The one mapping from neutral column types to PostgreSQL and SQL Server types.

The neutral vocabulary is docs/contracts.md#object-model (docs/formats/model.md, "Neutral column
types"). relink-scan (S3.relink_scan) prints this mapping; stage1 (S3.move) and S4.models build
their tables from it, so the two never disagree.

- `sql_type(column, dialect)`: the column's type as DDL text (lowercase), without NOT NULL,
  defaults or identity.
- `ddl(column, dialect)`: the full column definition text: type plus identity, NOT NULL and
  server default where the mapping adds them (autonumber, yesno).
- `sa_type(column)`: a SQLAlchemy type with an explicit `postgresql` and `mssql` variant.
- `sa_column(column)`: a SQLAlchemy Column with the identity and the yesno NOT NULL default.
- `needs_rowversion(table)` and `extra_columns(table, dialect)`: on SQL Server a table with a
  `single` or `double` column gets `mp_rowversion rowversion`, so Access compares that column
  instead of every float and stops reporting write conflicts.

`complex` and `oleobject` columns are omitted (not created, not loaded) and listed by relink-scan.
Any other type raises `UnsupportedType`.
"""

from __future__ import annotations

import sqlalchemy as sa
from sqlalchemy import types as satypes
from sqlalchemy.dialects import mssql
from sqlalchemy.dialects import postgresql as pg

DIALECTS = ("postgresql", "mssql")
DIALECT_TITLES = {"postgresql": "PostgreSQL", "mssql": "SQL Server"}

NEUTRAL_TYPES = (
    "text",
    "memo",
    "byte",
    "integer",
    "longinteger",
    "autonumber",
    "single",
    "double",
    "currency",
    "decimal",
    "datetime",
    "yesno",
    "hyperlink",
    "oleobject",
    "complex",
    "guid",
)
OMITTED_TYPES = ("complex", "oleobject")
FLOAT_TYPES = ("single", "double")
MAPPED_TYPES = tuple(t for t in NEUTRAL_TYPES if t not in OMITTED_TYPES)

DEFAULT_TEXT_SIZE = 255  # Access's default Short Text size when the design gives none
DEFAULT_DECIMAL = (18, 0)  # Access's default Decimal precision and scale
ROWVERSION_COLUMN = "mp_rowversion"
PG_MAX_IDENTIFIER_BYTES = 63

# Type text per dialect; "{n}", "{p}" and "{s}" are filled from the column.
_TYPE_TEXT = {
    "text": ("varchar({n})", "nvarchar({n})"),
    "memo": ("text", "nvarchar(max)"),
    "byte": ("smallint", "tinyint"),
    "integer": ("smallint", "smallint"),
    "longinteger": ("integer", "int"),
    "autonumber": ("integer", "int"),
    "single": ("real", "real"),
    "double": ("double precision", "float(53)"),
    "currency": ("numeric(19,4)", "decimal(19,4)"),
    "decimal": ("numeric({p},{s})", "decimal({p},{s})"),
    "datetime": ("timestamp(0)", "datetime2(0)"),
    "yesno": ("boolean", "bit"),
    "hyperlink": ("text", "nvarchar(max)"),
    "guid": ("uuid", "uniqueidentifier"),
}
# What the mapping adds after the type, per dialect.
_SUFFIX = {
    "autonumber": ("GENERATED BY DEFAULT AS IDENTITY", "IDENTITY(1,1)"),
    "yesno": ("NOT NULL DEFAULT false", "NOT NULL DEFAULT 0"),
}


class UnsupportedType(Exception):
    """A column type with no mapping. str() names the type only."""

    def __init__(self, type_name):
        self.type_name = type_name
        super().__init__(f"unsupported type {type_name!r}")


def _type_of(column) -> str:
    return column if isinstance(column, str) else column.get("type")


def _dialect_index(dialect: str) -> int:
    if dialect not in DIALECTS:
        raise ValueError(f"unknown dialect {dialect!r}")
    return DIALECTS.index(dialect)


def is_omitted(column) -> bool:
    return _type_of(column) in OMITTED_TYPES


def is_supported(column, dialect: str | None = None) -> bool:
    """True for a mapped or omitted type (omitted types are listed, never unsupported)."""
    t = _type_of(column)
    if dialect is not None:
        _dialect_index(dialect)
    return t in MAPPED_TYPES or t in OMITTED_TYPES


def _size(column) -> int:
    size = None if isinstance(column, str) else column.get("size")
    return int(size) if isinstance(size, int) and size > 0 else DEFAULT_TEXT_SIZE


def _precision_scale(column) -> tuple[int, int]:
    if isinstance(column, str):
        return DEFAULT_DECIMAL
    p = column.get("precision")
    s = column.get("scale")
    p = int(p) if isinstance(p, int) and p > 0 else DEFAULT_DECIMAL[0]
    s = int(s) if isinstance(s, int) and s >= 0 else DEFAULT_DECIMAL[1]
    return p, s


def type_template(type_name: str, dialect: str) -> str:
    """The generic type text (`varchar(n)`, `numeric(p,s)`) for documentation."""
    i = _dialect_index(dialect)
    if type_name not in _TYPE_TEXT:
        raise UnsupportedType(type_name)
    text = _TYPE_TEXT[type_name][i].format(n="n", p="p", s="s")
    suffix = _SUFFIX.get(type_name)
    return f"{text} {suffix[i]}" if suffix else text


def sql_type(column, dialect: str) -> str | None:
    """Type text for a column dict (or a bare type name); None for an omitted type."""
    t = _type_of(column)
    i = _dialect_index(dialect)
    if t in OMITTED_TYPES:
        return None
    if t not in _TYPE_TEXT:
        raise UnsupportedType(t)
    p, s = _precision_scale(column)
    return _TYPE_TEXT[t][i].format(n=_size(column), p=p, s=s)


def ddl(column, dialect: str) -> str | None:
    """Full column definition text after the name; None for an omitted type."""
    base = sql_type(column, dialect)
    if base is None:
        return None
    suffix = _SUFFIX.get(_type_of(column))
    return f"{base} {suffix[_dialect_index(dialect)]}" if suffix else base


def sa_type(column) -> satypes.TypeEngine | None:
    """SQLAlchemy type with explicit postgresql and mssql variants; None for an omitted type."""
    t = _type_of(column)
    if t in OMITTED_TYPES:
        return None
    if t not in _TYPE_TEXT:
        raise UnsupportedType(t)
    n = _size(column)
    p, s = _precision_scale(column)
    pair = {
        "text": (pg.VARCHAR(n), mssql.NVARCHAR(n)),
        "memo": (pg.TEXT(), mssql.NVARCHAR(None)),
        "byte": (pg.SMALLINT(), mssql.TINYINT()),
        "integer": (pg.SMALLINT(), mssql.SMALLINT()),
        "longinteger": (pg.INTEGER(), mssql.INTEGER()),
        "autonumber": (pg.INTEGER(), mssql.INTEGER()),
        "single": (pg.REAL(), mssql.REAL()),
        "double": (pg.DOUBLE_PRECISION(), mssql.FLOAT(53)),
        "currency": (pg.NUMERIC(19, 4), mssql.DECIMAL(19, 4)),
        "decimal": (pg.NUMERIC(p, s), mssql.DECIMAL(p, s)),
        "datetime": (pg.TIMESTAMP(precision=0), mssql.DATETIME2(precision=0)),
        "yesno": (pg.BOOLEAN(), mssql.BIT()),
        "hyperlink": (pg.TEXT(), mssql.NVARCHAR(None)),
        "guid": (pg.UUID(), mssql.UNIQUEIDENTIFIER()),
    }[t]
    generic = {
        "text": satypes.String(n),
        "memo": satypes.Text(),
        "byte": satypes.SmallInteger(),
        "integer": satypes.SmallInteger(),
        "longinteger": satypes.Integer(),
        "autonumber": satypes.Integer(),
        "single": satypes.REAL(),
        "double": satypes.Float(53),
        "currency": satypes.Numeric(19, 4),
        "decimal": satypes.Numeric(p, s),
        "datetime": satypes.DateTime(),
        "yesno": satypes.Boolean(create_constraint=False),
        "hyperlink": satypes.Text(),
        "guid": satypes.Uuid(),
    }[t]
    return generic.with_variant(pair[0], "postgresql").with_variant(pair[1], "mssql")


def sa_column(column: dict, *, primary_key: bool = False) -> sa.Column | None:
    """SQLAlchemy Column for a model column; None for an omitted type.

    autonumber gets an Identity (PostgreSQL GENERATED BY DEFAULT AS IDENTITY, SQL Server
    IDENTITY(1,1)); yesno is NOT NULL with a false default; other columns keep `required`."""
    t = _type_of(column)
    typ = sa_type(column)
    if typ is None:
        return None
    args: list = [column["name"], typ]
    kwargs: dict = {"primary_key": primary_key}
    if t == "autonumber":
        args.append(sa.Identity(always=False, start=1, increment=1))
        kwargs["nullable"] = False
    elif t == "yesno":
        kwargs["nullable"] = False
        kwargs["server_default"] = sa.false()
    else:
        kwargs["nullable"] = not (primary_key or bool(column.get("required")))
    return sa.Column(*args, **kwargs)


def needs_rowversion(table: dict) -> bool:
    return any(c.get("type") in FLOAT_TYPES for c in table.get("columns", []))


def extra_columns(table: dict, dialect: str) -> list[sa.Column]:
    """Columns the mapping adds to a table: mp_rowversion on SQL Server for float tables."""
    _dialect_index(dialect)
    if dialect == "mssql" and needs_rowversion(table):
        return [sa.Column(ROWVERSION_COLUMN, mssql.ROWVERSION(), nullable=False)]
    return []


def too_long_for_postgresql(name: str) -> bool:
    return len(name.encode("utf-8")) > PG_MAX_IDENTIFIER_BYTES
