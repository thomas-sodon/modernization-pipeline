"""Write the per-stage Workflow launcher that calls run-stage.js with every file it needs embedded.

Workflow scripts cannot read files, and a Workflow script file may be at most 524288 bytes. pipeline.json
alone is about 500 KB as compact JSON, so the launcher embeds a slice of it: the top-level keys, the stage being run in
full, and every other stage reduced to the keys the driver reads from it (id, slug, title, applies_to,
offers, offer_note, bootstrap_only). The driver's dry run is the same for the slice and the full file
(tests/driver/run-stage.test.mjs checks this).

In the pipeline repo this file is .claude/workflows/make-launcher.py. Run it with the standard library only:

  python3 -I <pipeline>/.claude/workflows/make-launcher.py \
      --pipeline <pipeline> --records <records dir> --stage S2 --args <args.json> --out <launcher path>
      [--prior]          embed prior and prior_items from <records>/runs/<stage>.json (or S1-CO-NNN.json)

<args.json> holds the driver args that are not files: paths, dry_run or prepared, attempt, rerun, since,
items, change_order, host_attested, commit_trailer, max_agents, allow_over_budget, checkpoint. It must not
contain pipeline, engagement, gates, prior or prior_items; this script adds those from disk.
Then call: Workflow({ scriptPath: "<launcher path>" }). docs/runbook.md 2(f) gives the exact commands.
Exit codes: 0 written; 2 bad input or a launcher over the size limit.
"""
import argparse
import json
import sys
from pathlib import Path

LIMIT = 500_000  # bytes; the Workflow tool refuses script files over 524288 bytes
STUB_KEYS = ("id", "slug", "title", "applies_to", "offers", "offer_note", "bootstrap_only")
FILE_KEYS = ("pipeline", "engagement", "gates", "prior", "prior_items")


def fail(msg):
    print(f"make-launcher: {msg}", file=sys.stderr)
    sys.exit(2)


def load(path, what):
    try:
        return json.loads(Path(path).read_text(encoding="utf-8"))
    except FileNotFoundError:
        fail(f"{what} not found: {path}")
    except json.JSONDecodeError as e:
        fail(f"{what} is not valid JSON ({path}): {e}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pipeline", required=True, help="pipeline checkout (holds pipeline.json and .claude/workflows/run-stage.js)")
    ap.add_argument("--records", required=True, help="records dir (engagement.json, gates.json, runs/)")
    ap.add_argument("--stage", required=True)
    ap.add_argument("--args", required=True, help="JSON file with the non-file driver args")
    ap.add_argument("--out", required=True)
    ap.add_argument("--prior", action="store_true", help="embed prior and prior_items from runs/<stage>.json")
    ap.add_argument("--driver", default=None, help="driver path (default <pipeline>/.claude/workflows/run-stage.js)")
    o = ap.parse_args()

    pipe = Path(o.pipeline)
    rec = Path(o.records)
    if not pipe.is_absolute() or not rec.is_absolute() or not Path(o.out).is_absolute():
        fail("--pipeline, --records and --out must be absolute paths")
    driver = Path(o.driver) if o.driver else pipe / ".claude" / "workflows" / "run-stage.js"
    if not driver.is_file():
        fail(f"driver not found: {driver}")

    p = load(pipe / "pipeline.json", "pipeline.json")
    ids = [s.get("id") for s in p.get("stages", [])]
    if o.stage not in ids:
        fail(f"unknown stage {o.stage}; pipeline.json has {', '.join(map(str, ids))}")
    sliced = {k: v for k, v in p.items() if k != "stages"}
    sliced["stages"] = [s if s.get("id") == o.stage else {k: s[k] for k in STUB_KEYS if k in s} for s in p["stages"]]

    args = load(o.args, "--args file")
    if not isinstance(args, dict):
        fail("--args must hold a JSON object")
    bad = [k for k in FILE_KEYS if k in args]
    if bad:
        fail(f"--args must not contain {', '.join(bad)}; they are read from disk")
    args = dict(args, stage_id=o.stage)

    files = {"pipeline": sliced, "engagement": load(rec / "engagement.json", "engagement.json")}
    gates = rec / "gates.json"
    if gates.exists():
        files["gates"] = load(gates, "gates.json")
    if o.prior:
        co = args.get("change_order")
        runs = rec / "runs" / (f"{o.stage}-{co}.json" if co else f"{o.stage}.json")
        r = load(runs, "the stage report")
        files["prior"] = r.get("results") or {}
        if r.get("items"):
            files["prior_items"] = r["items"]

    payload = json.dumps({**args, **files}, ensure_ascii=False, separators=(",", ":"))
    text = (
        "export const meta = { name: 'launch-" + o.stage.lower() + "', "
        "description: 'Run " + o.stage + " through run-stage.js with pipeline.json (sliced), engagement.json, gates.json and prior embedded' }\n"
        "// Generated by make-launcher.py; do not edit. Regenerate after any change to the embedded files.\n"
        f"const A = {payload}\n"
        f"return await workflow({{ scriptPath: {json.dumps(str(driver))} }}, A)\n"
    )
    size = len(text.encode("utf-8"))
    if size > LIMIT:
        fail(f"launcher would be {size} bytes, over {LIMIT}; drop prior or split the stage report")
    Path(o.out).write_text(text, encoding="utf-8")
    print(json.dumps({"launcher": o.out, "bytes": size, "stage": o.stage, "prior": bool(o.prior)}))


if __name__ == "__main__":
    main()
